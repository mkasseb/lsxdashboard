#!/usr/bin/env node
'use strict';
const assert=require('node:assert/strict'),c=require('../assets/weather-contracts');
const now=Date.parse('2026-10-16T18:00:00Z'),H=3600000;
const stamp=ms=>new Date(ms).toISOString();
const field=(value,unitCode)=>({value,unitCode});
const near=(actual,expected)=>assert(Math.abs(actual-expected)<0.001,`${actual} != ${expected}`);
assert.equal(c.measurement(field(0,'wmoUnit:degF'),'temperature'),0);
assert.equal(c.measurement(field(0,'wmoUnit:degC'),'temperature'),32);
near(c.measurement(field(273.15,'wmoUnit:K'),'temperature'),32);
near(c.measurement(field(10,'wmoUnit:mi_h-1'),'wind'),10);
near(c.measurement(field(16.09344,'wmoUnit:km_h-1'),'wind'),10);
near(c.measurement(field(10,'wmoUnit:m_s-1'),'wind'),22.36936);
near(c.measurement(field(10,'wmoUnit:kn'),'wind'),11.50779);
near(c.measurement(field(1013.25,'wmoUnit:hPa'),'pressure'),29.9213);
near(c.measurement(field(1.60934,'wmoUnit:km'),'visibility'),1);
for(const value of [null,'',false,'0',NaN,Infinity])assert.equal(c.measurement(field(value),'temperature'),null);
for(const kind of ['temperature','wind','pressure','visibility','humidity','direction'])assert.equal(c.measurement(field(10,'unexpected'),kind),null);
assert.equal(c.measurement(field(-1),'wind'),null);
assert.equal(c.measurement(field(101),'humidity'),null);
assert.equal(c.measurement(field(361),'direction'),null);
assert.equal(c.sourceState(stamp(now-2*H),now,2*H).state,'ready');
assert.equal(c.sourceState(stamp(now-2*H-1),now,2*H).state,'stale');
assert.equal(c.sourceState(stamp(now+c.policy.clockSkew),now,H).state,'ready');
assert.equal(c.sourceState(stamp(now+c.policy.clockSkew+1),now,H).state,'unknown');
for(const value of [null,'bad',0,NaN])assert.equal(c.sourceState(value,now,H).state,'unknown');
const observation={properties:{timestamp:stamp(now),temperature:field(0,'wmoUnit:degF'),windSpeed:field(0),relativeHumidity:field(50)}};
assert.equal(c.observation(observation,now,null,true).temperature,0);
assert.equal(c.observation(observation,now,null,true).wind,0);
observation.properties.temperature.value=null;
assert.equal(c.observation(observation,now,null,true),null);
assert.equal(c.observation(observation,now,null,false).humidity,50);
assert.equal(c.airQuality({current:{time:now/1000,us_aqi:0,pm2_5:0}},now).value,0);
assert.equal(c.airQuality({current:{time:(now-3*H)/1000,us_aqi:75}},now),null);
assert.equal(c.airQuality({current:{time:now/1000,us_aqi:'75'}},now),null);
const uv={hourly:{time:[now/1000,(now+H)/1000],uv_index:[0,6]},daily:{time:['2026-10-16','2026-02-30'],uv_index_max:[6,9]}};
assert.deepEqual(c.uv(uv,now),{now:0,peak:{v:6,t:now+H},daily:{'2026-10-16':6}});
assert.equal(c.uv({hourly:{time:[now/1000],uv_index:['bad']}},now),null);
assert.equal(c.uv({hourly:{time:['2026-10-16T13:00:00'],uv_index:[6]}},now),null,'offset-free timestamps do not inherit the viewer timezone');
const period={name:'Today',isDaytime:true,temperature:0,temperatureUnit:'C',windSpeed:'16 to 32 km/h',shortForecast:'Clear',startTime:stamp(now-H),endTime:stamp(now+H)};
const forecast=c.forecast({properties:{periods:[{...period,endTime:stamp(now)},period,{...period,temperatureUnit:'K'}]}},now);
assert.equal(forecast.properties.periods.length,1);
assert.equal(forecast.properties.periods[0].temperature,32);
assert.equal(forecast.properties.periods[0].windSpeed,'10 to 20 mph');
assert.equal(period.temperature,0,'normalization cannot mutate the source');
assert.equal(c.forecast({properties:{periods:[{...period,temperature:null}]}},now),null);
assert(c.arcgis({features:[]}));assert(!c.arcgis({error:{code:500},features:[]}));assert(!c.arcgis({features:[null]}));
assert(c.mapStyle({version:8,sources:{},layers:[]}));assert(!c.mapStyle({}));
console.log('PASS shared units, finite/missing values, source-age/clock boundaries, independent observations, AQI, UV/DST dates, forecasts and metadata contracts');
